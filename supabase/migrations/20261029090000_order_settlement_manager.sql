-- 수주의 정산 담당 (2026-10-29)
-- 공사 하나의 정산(기성·준공 계산서)은 한 사람 몫이다. 대시보드 담당자별 '정산' 칸은 이 칸으로만 나뉜다.
--   시공 담당 = 공사이력.담당공무_id (행마다)  /  정산 담당 = 수주.정산담당자_id (공사마다)
-- 비어 있으면 '정산 미지정'으로 드러난다 — 책임 공무(공무담당자_id)로 조용히 대체하지 않는다(잊으면 화면에 보여야 고친다).
-- 기성.담당공무_id 는 더 이상 입력·집계에 쓰지 않는다(값은 남겨 둔다). 정산 담당 장부를 두 개 두지 않기 위해.
-- RLS: 정책은 테이블(수주)에 붙어 있으므로 이 칸도 같은 화이트리스트 정책으로 보호된다.
-- ⚠️ ERP 코드 배포 전에 먼저 적용할 것 — 코드가 이 칸을 select 하므로 없으면 KPI 조회가 실패한다.
alter table public.수주
  add column if not exists 정산담당자_id bigint references public.공무담당자(id);

-- 기존 수주 일괄 채우기 (일회성, 2026-10-29 사용자 결정)
--   단가 → 김도윤 (단가공사 정산은 김도윤 담당)  /  총가 → 김무선  /  민수·관급·구분없음 → 비워 둠('정산 미지정'으로 드러남)
-- 새 칸이라 덮어쓸 기존 값이 없다. 되돌리려면: update public.수주 set 정산담당자_id = null;
-- 이름으로 찾는다 — 그 이름이 없으면 서브쿼리가 null 이라 아무것도 채워지지 않는다(틀린 사람에게 붙지 않는다)
update public.수주
   set 정산담당자_id = (select id from public.공무담당자 where 이름 = '김도윤')
 where 공사구분 = '단가' and 정산담당자_id is null;

update public.수주
   set 정산담당자_id = (select id from public.공무담당자 where 이름 = '김무선')
 where 공사구분 = '총가' and 정산담당자_id is null;

