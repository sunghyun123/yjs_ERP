import { describe, it, expect } from 'vitest'
import { build월성과내역, sum월성과내역 } from './monthly-revenue-breakdown'
import { build이력누계, type 공사이력Row, type 준공수주Row } from './junggong-seonggwa'
import type { 투입실적With상세 } from './calc'

const 수주 = (over: Partial<준공수주Row> & { id: number }): 준공수주Row => ({
  지중no: `JG26-${String(over.id).padStart(3, '0')}`,
  공사명: `테스트 공사 ${over.id}`,
  공사구분: '지중',
  준공여부: false,
  준공일: null,
  준공액_공급가: null,
  수주금액_공급가: 10_000_000,
  보험료율: null,
  하도전용율: null,
  ...over,
})

const 이력 = (수주_id: number, 작업일자: string, 성과금액: number | null): 공사이력Row =>
  ({ 수주_id, 작업일자, 성과금액 })

/** 야간 판정에 쓰이는 필드만 채운 투입실적 — 나머지 컬럼은 이 계산에 쓰이지 않는다 */
const 투입 = (수주_id: number, 투입일: string, 야간: boolean): 투입실적With상세 =>
  ({
    수주_id,
    투입일,
    투입실적상세: [{ 투입구분: '상용직', 주간수량: 2, 야간수량: 야간 ? 1 : 0 }],
  }) as unknown as 투입실적With상세

const 이번달 = ['2026-09-01', '2026-10-01'] as const

describe('build월성과내역', () => {
  it('공사별로 성과금액을 합치고 성과가 찍힌 날을 모은다', () => {
    const rows = build월성과내역(
      [이력(1, '2026-09-03', 1_200_000), 이력(1, '2026-09-11', 800_000), 이력(2, '2026-09-05', 500_000)],
      [수주({ id: 1 }), 수주({ id: 2 })],
      new Map(),
      [],
      ...이번달,
    )
    expect(rows).toHaveLength(2)
    expect(rows[0]).toMatchObject({ 수주_id: 1, 지중no: 'JG26-001', 금액천원: 2000, 일자: [3, 11] })
    expect(rows[1]).toMatchObject({ 수주_id: 2, 금액천원: 500, 일자: [5] })
  })

  it('기간 밖 공사이력은 금액에도 날짜에도 안 들어간다', () => {
    const rows = build월성과내역(
      [이력(1, '2026-08-31', 9_000_000), 이력(1, '2026-09-02', 1_000_000), 이력(1, '2026-10-01', 9_000_000)],
      [수주({ id: 1 })],
      new Map(),
      [],
      ...이번달,
    )
    expect(rows[0]).toMatchObject({ 금액천원: 1000, 일자: [2] })
  })

  it('야간 투입이 있던 날만 야간일자에 담는다', () => {
    const rows = build월성과내역(
      [이력(1, '2026-09-03', 1_000_000), 이력(1, '2026-09-04', 1_000_000), 이력(1, '2026-09-05', 1_000_000)],
      [수주({ id: 1 })],
      new Map(),
      // 4일은 주간만, 5일은 야간 있음, 3일은 투입 입력 자체가 없음
      [투입(1, '2026-09-04', false), 투입(1, '2026-09-05', true)],
      ...이번달,
    )
    expect(rows[0].일자).toEqual([3, 4, 5])
    expect(rows[0].야간일자).toEqual([5])
  })

  it('다른 공사의 야간 투입은 옮겨붙지 않는다', () => {
    const rows = build월성과내역(
      [이력(1, '2026-09-07', 1_000_000)],
      [수주({ id: 1 }), 수주({ id: 2 })],
      new Map(),
      [투입(2, '2026-09-07', true)],
      ...이번달,
    )
    expect(rows[0].야간일자).toEqual([])
  })

  it('준공 잔여성과는 같은 공사의 이력과 한 줄로 합쳐진다', () => {
    const 이력목록 = [이력(1, '2026-09-02', 4_000_000)]
    const rows = build월성과내역(
      이력목록,
      [수주({ id: 1, 준공여부: true, 준공일: '2026-09-20', 준공액_공급가: 10_000_000 })],
      build이력누계(이력목록),
      [],
      ...이번달,
    )
    // 이력 4,000,000 + 준공 잔여 (10,000,000 - 4,000,000) = 10,000,000
    expect(rows).toHaveLength(1)
    expect(rows[0]).toMatchObject({ 금액천원: 10_000, 일자: [2] })
  })

  it('그 달 작업이 없이 준공만 있으면 날짜가 빈 행이 된다', () => {
    // 작년에 성과가 다 잡히고 이번 달에 준공만 찍은 공사 — 화면에서 날짜 줄을 안 그리는 경우
    const 지난이력 = [이력(1, '2025-11-10', 12_000_000)]
    const rows = build월성과내역(
      지난이력,
      [수주({ id: 1, 준공여부: true, 준공일: '2026-09-20', 준공액_공급가: 10_000_000 })],
      build이력누계(지난이력),
      [],
      ...이번달,
    )
    expect(rows).toHaveLength(1)
    expect(rows[0]).toMatchObject({ 금액천원: -2000, 일자: [], 야간일자: [] })
  })

  it('합계가 0천원이 되는 공사는 표에서 감춘다 (총액은 그대로)', () => {
    const rows = build월성과내역(
      [이력(1, '2026-09-02', 300), 이력(2, '2026-09-02', 5_000_000)],
      [수주({ id: 1 }), 수주({ id: 2 })],
      new Map(),
      [],
      ...이번달,
    )
    expect(rows.map((r) => r.수주_id)).toEqual([2])
    expect(sum월성과내역(rows)).toBe(5000)
  })

  it('금액 큰 순으로 정렬한다', () => {
    const rows = build월성과내역(
      [이력(1, '2026-09-02', 1_000_000), 이력(2, '2026-09-02', 9_000_000), 이력(3, '2026-09-02', 5_000_000)],
      [수주({ id: 1 }), 수주({ id: 2 }), 수주({ id: 3 })],
      new Map(),
      [],
      ...이번달,
    )
    expect(rows.map((r) => r.금액천원)).toEqual([9000, 5000, 1000])
  })
})

describe('sum월성과내역 — 도넛과 표가 어긋나지 않는다는 제약', () => {
  it('총액은 화면에 보이는 행들을 그대로 더한 값이다', () => {
    // 행마다 반올림으로 최대 500원씩 깎이므로, 원 단위로 다 더한 뒤 반올림한 값과는 달라질 수 있다.
    // 표를 손으로 더하는 사람과 맞춰야 하므로 '행의 합'이 정본이다.
    const 이력목록 = [
      이력(1, '2026-09-02', 1_000_499),
      이력(2, '2026-09-02', 2_000_499),
      이력(3, '2026-09-02', 3_000_499),
    ]
    const rows = build월성과내역(
      이력목록,
      [수주({ id: 1 }), 수주({ id: 2 }), 수주({ id: 3 })],
      new Map(),
      [],
      ...이번달,
    )
    expect(rows.map((r) => r.금액천원)).toEqual([3000, 2000, 1000])
    expect(sum월성과내역(rows)).toBe(6000)
    // 손으로 더한 값과 같다 — 이게 깨지면 사장님 눈에 '틀린 표'가 된다
    expect(sum월성과내역(rows)).toBe(rows.reduce((s, r) => s + r.금액천원, 0))
  })

  it('음수 행도 상계해서 합계에 반영한다', () => {
    const 지난이력 = [이력(9, '2025-11-10', 12_000_000)]
    const rows = build월성과내역(
      [...지난이력, 이력(1, '2026-09-02', 5_000_000)],
      [수주({ id: 1 }), 수주({ id: 9, 준공여부: true, 준공일: '2026-09-20', 준공액_공급가: 10_000_000 })],
      build이력누계(지난이력),
      [],
      ...이번달,
    )
    expect(sum월성과내역(rows)).toBe(3000) // 5,000 + (-2,000)
  })
})
