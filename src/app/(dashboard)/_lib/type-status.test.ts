import { describe, it, expect } from 'vitest'
import {
  유형상태집계,
  연도추출,
  연도목록,
  연도필터,
  기본연도,
  연도미상,
  type 수주도넛입력,
} from './type-status'

const 행 = (over: Partial<수주도넛입력>): 수주도넛입력 => ({
  지중no: 'JY25-001',
  공사구분: '단가',
  시공상태: '완료',
  준공여부: false,
  수주금액_공급가: 1_000_000,
  보험료율: null,
  하도전용율: null,
  ...over,
})

describe('유형상태집계', () => {
  it('같은 연도×유형×상태는 금액을 합산하고 건수를 센다', () => {
    const out = 유형상태집계([행({}), 행({ 수주금액_공급가: 500_000 })])
    expect(out).toEqual([{ 연도: 2025, 유형: '단가', 상태: '완료', 금액: 1_500_000, 건수: 2 }])
  })

  it('금액은 관대 하도적용(요율 있으면 적용, 없으면 공급가 그대로)', () => {
    const out = 유형상태집계([행({ 보험료율: 0.075, 하도전용율: 0.85 })])
    expect(out[0].금액).toBeCloseTo(1_000_000 * 0.925 * 0.85, 4)
  })

  it('관급은 민수로 합산된다 (사장님 피드백)', () => {
    const out = 유형상태집계([
      행({ 공사구분: '민수', 수주금액_공급가: 300_000 }),
      행({ 공사구분: '관급', 수주금액_공급가: 200_000 }),
    ])
    expect(out).toEqual([{ 연도: 2025, 유형: '민수', 상태: '완료', 금액: 500_000, 건수: 2 }])
  })

  it('시공상태를 차트 라벨로 바꾼다 (미시공→미진행, 시공중→진행중)', () => {
    const out = 유형상태집계([행({ 시공상태: '미시공' }), 행({ 시공상태: '시공중' })])
    expect(out.map((r) => r.상태).sort()).toEqual(['미진행', '진행중'])
  })

  it('공사구분·시공상태가 null이면 미분류로 잡는다 (조용히 버리지 않음)', () => {
    const out = 유형상태집계([행({ 공사구분: null, 시공상태: null })])
    expect(out).toEqual([{ 연도: 2025, 유형: '미분류', 상태: '미분류', 금액: 1_000_000, 건수: 1 }])
  })

  it('준공여부=true면 시공상태와 무관하게 완료 (실제 플로우가 쓰는 컬럼을 신뢰)', () => {
    const out = 유형상태집계([
      행({ 시공상태: null, 준공여부: true }),
      행({ 시공상태: '미시공', 준공여부: true }),
    ])
    expect(out).toEqual([{ 연도: 2025, 유형: '단가', 상태: '완료', 금액: 2_000_000, 건수: 2 }])
  })

  it('준공여부=false여도 시공상태=완료면 완료 (시공 완료, 준공 서류 전)', () => {
    const out = 유형상태집계([행({ 시공상태: '완료', 준공여부: false })])
    expect(out[0].상태).toBe('완료')
  })

  it('공급가 null은 금액 0으로 합산되지만 건수에는 포함된다', () => {
    const out = 유형상태집계([행({}), 행({ 수주금액_공급가: null })])
    expect(out).toEqual([{ 연도: 2025, 유형: '단가', 상태: '완료', 금액: 1_000_000, 건수: 2 }])
  })

  it('연도가 다르면 같은 유형×상태라도 분리된다 (연도가 집계 키의 일부)', () => {
    const out = 유형상태집계([행({ 지중no: 'JY25-001' }), 행({ 지중no: 'SG26-004' })])
    expect(out).toHaveLength(2)
    expect(out.map((r) => r.연도).sort()).toEqual([2025, 2026])
  })
})

describe('연도추출', () => {
  it('지중no 접두어 2글자 뒤 2자리를 2000년대 연도로 읽는다', () => {
    expect(연도추출('JY25-018')).toBe(2025)
    expect(연도추출('SG26-011')).toBe(2026)
    expect(연도추출('my26-004')).toBe(2026) // 소문자도 허용
  })

  it('명명 규칙에서 벗어나면 null (억지로 숫자를 짜내지 않는다)', () => {
    expect(연도추출('2025-001')).toBeNull() // 앞 2글자가 영문이 아님
    expect(연도추출('JY-018')).toBeNull() // 연도 자리 없음
    expect(연도추출('JYY25-1')).toBeNull() // 접두어 3글자
    expect(연도추출('')).toBeNull()
  })
})

describe('연도목록', () => {
  it('최신 연도부터 내림차순으로 준다 (드롭다운 순서)', () => {
    const rows = 유형상태집계([
      행({ 지중no: 'JY25-001' }),
      행({ 지중no: 'SG26-001' }),
      행({ 지중no: 'TY24-001' }),
    ])
    expect(연도목록(rows)).toEqual([2026, 2025, 2024])
  })

  it('연도를 못 읽은 행이 있으면 연도미상을 맨 뒤에 붙인다 (조용히 사라지지 않게)', () => {
    const rows = 유형상태집계([행({ 지중no: 'JY25-001' }), 행({ 지중no: '???' })])
    expect(연도목록(rows)).toEqual([2025, 연도미상])
  })

  it('연도미상 행이 없으면 그 옵션도 없다', () => {
    const rows = 유형상태집계([행({ 지중no: 'JY25-001' })])
    expect(연도목록(rows)).toEqual([2025])
  })
})

describe('연도필터', () => {
  const rows = 유형상태집계([
    행({ 지중no: 'JY25-001', 공사구분: '단가', 수주금액_공급가: 100 }),
    행({ 지중no: 'SG25-002', 공사구분: '단가', 수주금액_공급가: 200 }),
    행({ 지중no: 'JY26-003', 공사구분: '단가', 수주금액_공급가: 400 }),
    행({ 지중no: 'JY26-004', 공사구분: '민수', 수주금액_공급가: 800 }),
  ])

  it('특정 연도를 고르면 그 연도만 남는다', () => {
    expect(연도필터(rows, 2025)).toEqual([{ 유형: '단가', 상태: '완료', 금액: 300, 건수: 2 }])
  })

  it("'전체'는 연도를 넘어 유형×상태로 재합산한다 (연도가 키에서 빠짐)", () => {
    const out = 연도필터(rows, '전체')
    expect(out).toEqual([
      { 유형: '단가', 상태: '완료', 금액: 700, 건수: 3 },
      { 유형: '민수', 상태: '완료', 금액: 800, 건수: 1 },
    ])
  })

  it('전체 금액 = 각 연도 금액의 합 (연도 필터가 행을 잃지 않는다)', () => {
    const 합 = (rs: { 금액: number }[]) => rs.reduce((s, r) => s + r.금액, 0)
    const 연도별합 = 연도목록(rows).reduce<number>((s, y) => s + 합(연도필터(rows, y)), 0)
    expect(연도별합).toBe(합(연도필터(rows, '전체')))
  })

  it('연도미상을 고르면 규칙에서 벗어난 행만 나온다', () => {
    const 섞임 = 유형상태집계([행({ 지중no: 'JY25-001' }), 행({ 지중no: '???', 수주금액_공급가: 7 })])
    expect(연도필터(섞임, 연도미상)).toEqual([{ 유형: '단가', 상태: '완료', 금액: 7, 건수: 1 }])
  })
})

describe('기본연도', () => {
  it('올해가 데이터에 있으면 올해를 연다', () => {
    const rows = 유형상태집계([행({ 지중no: 'JY25-001' }), 행({ 지중no: 'SG26-001' })])
    expect(기본연도(rows, 2026)).toBe(2026)
  })

  it('올해 수주가 아직 없으면 가장 최신 연도를 연다 (빈 도넛을 띄우지 않는다)', () => {
    const rows = 유형상태집계([행({ 지중no: 'JY25-001' })])
    expect(기본연도(rows, 2027)).toBe(2025)
  })

  it('데이터가 아예 없으면 전체 (고를 연도가 없다)', () => {
    expect(기본연도([], 2026)).toBe('전체')
  })
})
