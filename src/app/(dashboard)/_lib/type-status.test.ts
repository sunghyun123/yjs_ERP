import { describe, it, expect } from 'vitest'
import {
  공사행변환,
  유형상태집계,
  연도추출,
  연도목록,
  연도필터,
  기본연도,
  연도미상,
  type 수주도넛입력,
} from './type-status'

const 행 = (over: Partial<수주도넛입력>): 수주도넛입력 => ({
  지중no: 'JY25-001',
  공사명: '시청 앞 지중화',
  공사구분: '단가',
  준공여부: false,
  이력건수: 0,
  수주금액_공급가: 1_000_000,
  보험료율: null,
  하도전용율: null,
  ...over,
})

describe('공사행변환 — 상태 규칙(2026-07-15 재정의)', () => {
  it('준공여부=true면 이력이 있든 없든 완료 (완료 = 준공 기준, 달성률 100% 아님)', () => {
    const out = 공사행변환([행({ 준공여부: true, 이력건수: 0 }), 행({ 준공여부: true, 이력건수: 5 })])
    expect(out.map((r) => r.상태)).toEqual(['완료', '완료'])
  })

  it('준공 전이라도 공사이력이 1건 이상이면 진행중', () => {
    const out = 공사행변환([행({ 이력건수: 1 }), 행({ 이력건수: 12 })])
    expect(out.map((r) => r.상태)).toEqual(['진행중', '진행중'])
  })

  it('수주만 있고 공사이력이 0건이면 미진행 (수주 후 공사는 나중이 정상 흐름 — 디폴트 상태)', () => {
    const out = 공사행변환([행({ 이력건수: 0 })])
    expect(out[0].상태).toBe('미진행')
  })

  it('금액은 관대 하도적용(요율 있으면 적용, 없으면 공급가 그대로)', () => {
    const out = 공사행변환([행({ 보험료율: 0.075, 하도전용율: 0.85 })])
    expect(out[0].금액).toBeCloseTo(1_000_000 * 0.925 * 0.85, 4)
  })

  it('관급은 민수로 표시된다 (사장님 피드백)', () => {
    const out = 공사행변환([행({ 공사구분: '관급' })])
    expect(out[0].유형).toBe('민수')
  })

  it('공사구분이 null이면 유형 미분류로 잡는다 (조용히 버리지 않음)', () => {
    const out = 공사행변환([행({ 공사구분: null })])
    expect(out[0].유형).toBe('미분류')
  })

  it('지중no·공사명을 그대로 실어 나른다 (클릭 팝업 목록이 이걸 쓴다)', () => {
    const out = 공사행변환([행({ 지중no: 'SG26-011', 공사명: '한전 인입공사' })])
    expect(out[0]).toMatchObject({ 지중no: 'SG26-011', 공사명: '한전 인입공사', 연도: 2026 })
  })
})

describe('유형상태집계', () => {
  it('같은 유형×상태는 금액을 합산하고 건수를 센다', () => {
    const out = 유형상태집계(공사행변환([행({}), 행({ 지중no: 'JY25-002', 수주금액_공급가: 500_000 })]))
    expect(out).toEqual([{ 유형: '단가', 상태: '미진행', 금액: 1_500_000, 건수: 2 }])
  })

  it('공급가 null은 금액 0으로 합산되지만 건수에는 포함된다', () => {
    const out = 유형상태집계(공사행변환([행({}), 행({ 수주금액_공급가: null })]))
    expect(out).toEqual([{ 유형: '단가', 상태: '미진행', 금액: 1_000_000, 건수: 2 }])
  })

  it('상태가 다르면 같은 유형이라도 조각이 갈린다', () => {
    const out = 유형상태집계(공사행변환([행({ 이력건수: 3 }), 행({ 준공여부: true })]))
    expect(out.map((r) => r.상태).sort()).toEqual(['완료', '진행중'])
  })
})

describe('연도추출', () => {
  it('지중no 접두어 2글자 뒤 2자리를 2000년대 연도로 읽는다', () => {
    expect(연도추출('JY25-018')).toBe(2025)
    expect(연도추출('SG26-011')).toBe(2026)
    expect(연도추출('my26-004')).toBe(2026) // 소문자도 허용
  })

  it('명명 규칙에서 벗어나면 null (억지로 숫자를 짜내지 않는다)', () => {
    expect(연도추출('2025-001')).toBeNull() // 앞 2글자가 영문이 아님
    expect(연도추출('JY-018')).toBeNull() // 연도 자리 없음
    expect(연도추출('JYY25-1')).toBeNull() // 접두어 3글자
    expect(연도추출('')).toBeNull()
  })
})

describe('연도목록', () => {
  it('최신 연도부터 내림차순으로 준다 (드롭다운 순서)', () => {
    const rows = 공사행변환([
      행({ 지중no: 'JY25-001' }),
      행({ 지중no: 'SG26-001' }),
      행({ 지중no: 'TY24-001' }),
    ])
    expect(연도목록(rows)).toEqual([2026, 2025, 2024])
  })

  it('연도를 못 읽은 행이 있으면 연도미상을 맨 뒤에 붙인다 (조용히 사라지지 않게)', () => {
    const rows = 공사행변환([행({ 지중no: 'JY25-001' }), 행({ 지중no: '???' })])
    expect(연도목록(rows)).toEqual([2025, 연도미상])
  })

  it('연도미상 행이 없으면 그 옵션도 없다', () => {
    const rows = 공사행변환([행({ 지중no: 'JY25-001' })])
    expect(연도목록(rows)).toEqual([2025])
  })
})

describe('연도필터', () => {
  const rows = 공사행변환([
    행({ 지중no: 'JY25-001', 수주금액_공급가: 100 }),
    행({ 지중no: 'SG25-002', 수주금액_공급가: 200 }),
    행({ 지중no: 'JY26-003', 수주금액_공급가: 400 }),
    행({ 지중no: 'JY26-004', 공사구분: '민수', 수주금액_공급가: 800 }),
  ])

  it('특정 연도를 고르면 그 연도의 공사 행만 남는다', () => {
    expect(연도필터(rows, 2025).map((r) => r.지중no)).toEqual(['JY25-001', 'SG25-002'])
  })

  it("'전체'는 행을 그대로 둔다 (연도 필터가 행을 잃지 않는다)", () => {
    expect(연도필터(rows, '전체')).toHaveLength(4)
  })

  it('전체 금액 = 각 연도 금액의 합 (집계를 지나도 성립)', () => {
    const 합 = (rs: { 금액: number }[]) => rs.reduce((s, r) => s + r.금액, 0)
    const 연도별합 = 연도목록(rows).reduce<number>(
      (s, y) => s + 합(유형상태집계(연도필터(rows, y))),
      0,
    )
    expect(연도별합).toBe(합(유형상태집계(연도필터(rows, '전체'))))
  })

  it('연도미상을 고르면 규칙에서 벗어난 행만 나온다', () => {
    const 섞임 = 공사행변환([행({ 지중no: 'JY25-001' }), 행({ 지중no: '???', 수주금액_공급가: 7 })])
    expect(연도필터(섞임, 연도미상).map((r) => r.금액)).toEqual([7])
  })
})

describe('기본연도', () => {
  it('올해가 데이터에 있으면 올해를 연다', () => {
    const rows = 공사행변환([행({ 지중no: 'JY25-001' }), 행({ 지중no: 'SG26-001' })])
    expect(기본연도(rows, 2026)).toBe(2026)
  })

  it('올해 수주가 아직 없으면 가장 최신 연도를 연다 (빈 도넛을 띄우지 않는다)', () => {
    const rows = 공사행변환([행({ 지중no: 'JY25-001' })])
    expect(기본연도(rows, 2027)).toBe(2025)
  })

  it('데이터가 아예 없으면 전체 (고를 연도가 없다)', () => {
    expect(기본연도([], 2026)).toBe('전체')
  })
})
