import { describe, it, expect } from 'vitest'
import {
  build이력누계,
  calc준공잔여성과,
  sum준공잔여성과,
  type 준공수주Row,
} from './junggong-seonggwa'

const 수주 = (over: Partial<준공수주Row> & { id: number }): 준공수주Row => ({
  지중no: `JG26-${String(over.id).padStart(3, '0')}`,
  공사명: '테스트 공사',
  공사구분: '지중',
  준공여부: true,
  준공일: '2026-03-15',
  준공액_공급가: 10_000_000,
  수주금액_공급가: 10_000_000,
  보험료율: null,
  하도전용율: null,
  ...over,
})

const 올해 = ['2026-01-01', '2027-01-01'] as const
const 이번달 = ['2026-03-01', '2026-04-01'] as const

describe('build이력누계', () => {
  it('수주별로 성과금액을 합치고 null은 0으로 본다', () => {
    const m = build이력누계([
      { 수주_id: 1, 성과금액: 100 },
      { 수주_id: 1, 성과금액: null },
      { 수주_id: 1, 성과금액: 50 },
      { 수주_id: 2, 성과금액: 7 },
    ])
    expect(m.get(1)).toBe(150)
    expect(m.get(2)).toBe(7)
  })
})

describe('calc준공잔여성과', () => {
  it('준공액에서 공사이력 성과누계를 빼 준공월에 얹는다', () => {
    const r = calc준공잔여성과([수주({ id: 1 })], new Map([[1, 4_000_000]]), ...올해)
    expect(r).toEqual([{ 수주_id: 1, 준공일: '2026-03-15', 월: 2, 금액: 6_000_000 }])
  })

  // 143건 케이스: 기성만 있고 공사이력이 빈 공사 → 준공액 전액이 준공월 성과
  it('공사이력이 하나도 없으면 준공액 전액을 넣는다', () => {
    expect(calc준공잔여성과([수주({ id: 1 })], new Map(), ...올해)[0].금액).toBe(10_000_000)
  })

  // 이 규칙의 목적: 준공 공사의 성과 총액 == 준공액
  it('기존 성과누계 + 잔여성과 = 준공액', () => {
    const 누계 = 3_300_000
    const r = calc준공잔여성과([수주({ id: 1 })], new Map([[1, 누계]]), ...올해)
    expect(누계 + r[0].금액).toBe(10_000_000)
  })

  // 조용히 0으로 깎으면 틀린 값이 정상처럼 보인다 → 음수 그대로 노출
  it('성과누계가 준공액을 넘으면 음수를 그대로 돌려준다', () => {
    const r = calc준공잔여성과([수주({ id: 1, 준공액_공급가: 1_000 })], new Map([[1, 3_000]]), ...올해)
    expect(r[0].금액).toBe(-2_000)
  })

  it('준공 안 한 공사는 제외', () => {
    expect(calc준공잔여성과([수주({ id: 1, 준공여부: false })], new Map(), ...올해)).toEqual([])
  })

  it('준공일 또는 준공액이 비면 제외 (구ERP 이관 77건)', () => {
    expect(calc준공잔여성과([수주({ id: 1, 준공일: null })], new Map(), ...올해)).toEqual([])
    expect(calc준공잔여성과([수주({ id: 2, 준공액_공급가: null })], new Map(), ...올해)).toEqual([])
  })

  it('기간 밖에 준공한 건은 제외', () => {
    expect(calc준공잔여성과([수주({ id: 1, 준공일: '2025-12-31' })], new Map(), ...올해)).toEqual([])
  })

  it('from은 포함, to는 미포함 (경계)', () => {
    expect(calc준공잔여성과([수주({ id: 1, 준공일: '2026-03-01' })], new Map(), ...이번달)).toHaveLength(1)
    expect(calc준공잔여성과([수주({ id: 2, 준공일: '2026-03-31' })], new Map(), ...이번달)).toHaveLength(1)
    expect(calc준공잔여성과([수주({ id: 3, 준공일: '2026-04-01' })], new Map(), ...이번달)).toHaveLength(0)
  })

  it('연말/연초 경계를 문자열 그대로 읽는다 (UTC 밀림 없음)', () => {
    expect(calc준공잔여성과([수주({ id: 1, 준공일: '2026-01-01' })], new Map(), ...올해)[0].월).toBe(0)
    expect(calc준공잔여성과([수주({ id: 2, 준공일: '2026-12-31' })], new Map(), ...올해)[0].월).toBe(11)
  })

  it('작년에 잡힌 성과도 차감된다 — 누계는 전 기간이어야 한다', () => {
    // 2025년에 4백만 성과가 잡히고 2026년에 준공한 공사
    const 누계 = build이력누계([
      { 수주_id: 1, 성과금액: 4_000_000 }, // 2025년 행
      { 수주_id: 1, 성과금액: 1_000_000 }, // 2026년 행
    ])
    expect(calc준공잔여성과([수주({ id: 1 })], 누계, ...올해)[0].금액).toBe(5_000_000)
  })
})

describe('sum준공잔여성과', () => {
  it('음수 건도 그대로 상계한다', () => {
    const rows = calc준공잔여성과(
      [수주({ id: 1, 준공액_공급가: 5_000 }), 수주({ id: 2, 준공액_공급가: 1_000 })],
      new Map([[2, 3_000]]),
      ...올해,
    )
    expect(sum준공잔여성과(rows)).toBe(3_000) // 5,000 + (-2,000)
  })
})
