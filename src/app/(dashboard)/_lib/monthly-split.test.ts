import { describe, it, expect } from 'vitest'
import { build월정산내역, sum월정산내역, buildMonthlySplit, type 정산기성Row, type Split재료 } from './monthly-split'
import type { 준공수주Row } from './junggong-seonggwa'

const 수주 = (over: Partial<준공수주Row> & { id: number }): 준공수주Row => ({
  지중no: `JG26-${String(over.id).padStart(3, '0')}`,
  공사명: `테스트 공사 ${over.id}`,
  공사구분: '지중',
  준공여부: false,
  준공일: null,
  준공액_공급가: null,
  수주금액_공급가: 10_000_000,
  보험료율: null,
  하도전용율: null,
  ...over,
})

let 기성id = 0
const 기성 = (수주_id: number, 기성일: string | null, 금액: number | null, 차수: number | null = 1): 정산기성Row =>
  ({ id: ++기성id, 수주_id, 차수, 기성일, 기성액_공급가: 금액 })

const 이번달 = ['2026-09-01', '2026-10-01'] as const

describe('build월정산내역', () => {
  it('그 달 기성은 계산서 한 장당 한 줄, 구분은 "기성 N차"', () => {
    const rows = build월정산내역(
      [기성(1, '2026-09-23', 30_000_000, 2), 기성(1, '2026-08-20', 20_000_000, 1)],
      [수주({ id: 1 })],
      ...이번달,
    )
    expect(rows).toEqual([
      { 수주_id: 1, 지중no: 'JG26-001', 공사명: '테스트 공사 1', 구분: '기성 2차', 일: 23, 날짜: '2026-09-23', 금액천원: 30000, 담당공무_id: null, 담당: '' },
    ])
  })

  it('준공은 금회지불액 = 준공액 − 기성 전 기간 누계 (5월 기성 + 9월 준공)', () => {
    const rows = build월정산내역(
      [기성(1, '2026-05-10', 60_000_000)],
      [수주({ id: 1, 준공여부: true, 준공일: '2026-09-15', 준공액_공급가: 100_000_000 })],
      ...이번달,
    )
    expect(rows).toEqual([
      { 수주_id: 1, 지중no: 'JG26-001', 공사명: '테스트 공사 1', 구분: '준공', 일: 15, 날짜: '2026-09-15', 금액천원: 40000, 담당공무_id: null, 담당: '' },
    ])
  })

  it('기성이 없는 준공은 준공액 그대로', () => {
    const rows = build월정산내역(
      [],
      [수주({ id: 1, 준공여부: true, 준공일: '2026-09-02', 준공액_공급가: 5_000_000 })],
      ...이번달,
    )
    expect(rows[0]).toMatchObject({ 구분: '준공', 금액천원: 5000 })
  })

  it('환수(기성누계 > 준공액)는 음수 그대로 남고 합계에서 차감된다', () => {
    const rows = build월정산내역(
      [기성(1, '2026-06-01', 12_000_000), 기성(2, '2026-09-03', 3_000_000)],
      [
        수주({ id: 1, 준공여부: true, 준공일: '2026-09-10', 준공액_공급가: 10_000_000 }),
        수주({ id: 2 }),
      ],
      ...이번달,
    )
    expect(rows.map((r) => [r.수주_id, r.구분, r.금액천원])).toEqual([
      [2, '기성 1차', 3000],
      [1, '준공', -2000],
    ])
    expect(sum월정산내역(rows)).toBe(1000)
  })

  it('기성일이 빈 기성은 월 목록엔 없고 준공 차감에는 들어간다', () => {
    const rows = build월정산내역(
      [기성(1, null, 7_000_000)],
      [수주({ id: 1, 준공여부: true, 준공일: '2026-09-30', 준공액_공급가: 10_000_000 })],
      ...이번달,
    )
    expect(rows).toHaveLength(1)
    expect(rows[0]).toMatchObject({ 구분: '준공', 금액천원: 3000 })
  })

  it('달 경계: 말일은 넣고 다음 달 1일·전달 말일은 뺀다', () => {
    const rows = build월정산내역(
      [기성(1, '2026-08-31', 1_000_000), 기성(1, '2026-09-30', 2_000_000), 기성(1, '2026-10-01', 4_000_000)],
      [수주({ id: 1 })],
      ...이번달,
    )
    expect(rows.map((r) => r.일)).toEqual([30])
  })

  it('준공액이 비었거나 준공여부가 false면 준공 줄이 없다', () => {
    const rows = build월정산내역(
      [],
      [
        수주({ id: 1, 준공여부: true, 준공일: '2026-09-05', 준공액_공급가: null }),
        수주({ id: 2, 준공여부: false, 준공일: '2026-09-05', 준공액_공급가: 5_000_000 }),
      ],
      ...이번달,
    )
    expect(rows).toEqual([])
  })

  it('차수가 비어 있으면 구분은 "기성"', () => {
    const rows = build월정산내역([기성(1, '2026-09-05', 1_000_000, null)], [수주({ id: 1 })], ...이번달)
    expect(rows[0].구분).toBe('기성')
  })

  it('계산서 행마다 천원 반올림, 0천원 행은 감춘다', () => {
    const rows = build월정산내역(
      [기성(1, '2026-09-01', 499), 기성(2, '2026-09-02', 1_500)],
      [수주({ id: 1 }), 수주({ id: 2 })],
      ...이번달,
    )
    expect(rows.map((r) => [r.수주_id, r.금액천원])).toEqual([[2, 2]])
  })

  it('정렬: 금액 큰 순 → 지중no → 구분 → 일 (조회마다 순서 고정)', () => {
    const rows = build월정산내역(
      [기성(2, '2026-09-09', 1_000_000, 1), 기성(1, '2026-09-08', 1_000_000, 1), 기성(1, '2026-09-01', 9_000_000, 2)],
      [수주({ id: 1 }), 수주({ id: 2 })],
      ...이번달,
    )
    expect(rows.map((r) => [r.지중no, r.구분])).toEqual([
      ['JG26-001', '기성 2차'],
      ['JG26-001', '기성 1차'],
      ['JG26-002', '기성 1차'],
    ])
  })
})

describe('build월정산내역 — 정산 담당 (수주.정산담당자_id 한 곳에서, 2026-10-29)', () => {
  const 이름 = new Map([[8, '김도윤'], [7, '김무선']])

  it('기성·준공 모두 그 공사의 정산 담당을 따른다 — 공사 하나의 정산은 한 사람 몫', () => {
    const rows = build월정산내역(
      [기성(1, '2026-09-10', 30_000_000), 기성(2, '2026-05-01', 60_000_000)],
      [
        수주({ id: 1, 정산담당자_id: 8 }),
        수주({ id: 2, 정산담당자_id: 7, 준공여부: true, 준공일: '2026-09-20', 준공액_공급가: 100_000_000 }),
      ],
      ...이번달,
      이름,
    )
    expect(rows.map((r) => [r.구분, r.담당공무_id, r.담당])).toEqual([
      ['준공', 7, '김무선'],
      ['기성 1차', 8, '김도윤'],
    ])
  })

  it('정산 담당이 비면 빈 이름(정산 미지정) — 다른 칸으로 대신 채우지 않는다', () => {
    const rows = build월정산내역(
      [기성(1, '2026-09-10', 1_000_000)],
      [수주({ id: 1, 정산담당자_id: null })],
      ...이번달,
      이름,
    )
    expect(rows[0]).toMatchObject({ 담당공무_id: null, 담당: '' })
  })

  it('목록에서 지워진 담당은 공무 화면과 같은 이름으로 남긴다', () => {
    const rows = build월정산내역([기성(1, '2026-09-10', 1_000_000)], [수주({ id: 1, 정산담당자_id: 99 })], ...이번달, 이름)
    expect(rows[0].담당).toBe('삭제된 담당자 #99')
  })
})

describe('buildMonthlySplit — 재료 한 벌을 달마다 나눈다 (연간 응답, 2026-11-12)', () => {
  // 해 경계 양쪽에 한 행씩: 12/31은 12월, 1/1은 다음 해 1월
  const 수주 = [
    { id: 1, 지중no: 'A-1', 공사명: '갑', 공사구분: null, 준공여부: false, 준공일: null, 준공액_공급가: null,
      수주금액_공급가: 0, 보험료율: null, 하도전용율: null, 정산담당자_id: 7 },
  ] as unknown as 준공수주Row[]
  const 재료: Split재료 = {
    성과재료: {
      공사이력: [
        { 작업일자: '2026-12-31', 수주_id: 1, 성과금액: 1_000_000, 담당공무_id: 7 },
        { 작업일자: '2027-01-01', 수주_id: 1, 성과금액: 2_000_000, 담당공무_id: 7 },
      ],
      수주,
    },
    투입재료: { year: 2026, 투입실적: [], 단가: [] },
    기성전체: [{ id: 1, 수주_id: 1, 차수: 1, 기성일: '2026-12-31', 기성액_공급가: 500_000 }],
    담당이름: new Map([[7, '김무선']]),
  }

  it('같은 재료로 두 달을 계산하면 경계 행이 정확히 한 달에만 들어간다', () => {
    const 십이월 = buildMonthlySplit(재료, { 월: '2026-12', from: '2026-11-30', to: '2027-01-01' })
    const 일월 = buildMonthlySplit(재료, { 월: '2027-01', from: '2027-01-01', to: '2027-02-01' })
    expect(십이월.construction.totalThousand).toBe(1000)
    expect(일월.construction.totalThousand).toBe(2000)
    expect(십이월.settlement.totalThousand).toBe(500)
    expect(일월.settlement.totalThousand).toBe(0)
  })

  it('기간 칸과 담당 이름을 그대로 싣는다', () => {
    const s = buildMonthlySplit(재료, { 월: '2026-12', from: '2026-11-30', to: '2027-01-01' })
    expect(s).toMatchObject({ month: '2026-12', from: '2026-11-30', to: '2027-01-01' })
    expect(s.construction.rows[0].담당별[0].담당).toBe('김무선') // 시공 담당은 이력 행마다 → 담당별 배열
    expect(s.settlement.rows[0].담당).toBe('김무선')
  })

  it('재료를 바꾸지 않는다 — 12번 불러도 같은 원본을 본다', () => {
    const 전 = JSON.stringify({ ...재료, 담당이름: [...재료.담당이름] })
    buildMonthlySplit(재료, { 월: '2026-12', from: '2026-11-30', to: '2027-01-01' })
    buildMonthlySplit(재료, { 월: '2027-01', from: '2027-01-01', to: '2027-02-01' })
    expect(JSON.stringify({ ...재료, 담당이름: [...재료.담당이름] })).toBe(전)
  })
})
