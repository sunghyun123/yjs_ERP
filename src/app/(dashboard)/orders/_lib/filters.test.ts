import { describe, it, expect } from 'vitest'
import {
  수주필터,
  연도선택목록,
  원청사ID,
  원청사값,
  원청사목록,
  원청사없음ID,
  원청사없음존재,
  초기필터,
  필터적용중,
  type 수주필터조건,
} from './filters'
import { 연도미상 } from '../../_lib/수주분류'
import type { 수주행 } from '../_types'

// 수주행은 필드가 많다 — 필터가 읽는 것만 의미 있게 두고 나머지는 기본값으로 채운다.
const 행 = (over: Partial<수주행>): 수주행 => ({
  id: 1,
  지중no: 'JY25-001',
  공사번호: null,
  공사명: '시청 앞 지중화',
  공사구분: '단가',
  공사종류: null,
  공사현장: null,
  작업구분: null,
  시공상태: null,
  준공여부: false,
  착공일: null,
  준공일: null,
  수주금액_공급가: 1_000_000,
  준공액_공급가: null,
  달성율: null,
  참고사항: null,
  보험료율: null,
  하도전용율: null,
  발주자_id: null,
  원청사_id: 10,
  공사담당: null,
  감독자: null,
  정산상태: null,
  포장여부: false,
  자재청구여부: false,
  공무담당자_id: null,
  발주자: null,
  원청사: { 거래처명: '정우전설' },
  기성: [],
  이력건수: 0,
  ...over,
})

const 조건 = (over: Partial<수주필터조건> = {}): 수주필터조건 => ({ ...초기필터, ...over })

describe('수주필터 — 연도', () => {
  const rows = [
    행({ 지중no: 'JY25-001' }),
    행({ 지중no: 'SG25-002' }),
    행({ 지중no: 'JY26-003' }),
    행({ 지중no: '???' }),
  ]

  it('연도를 고르면 그 연도 행만 남는다', () => {
    expect(수주필터(rows, 조건({ 연도: 2025 })).map((r) => r.지중no)).toEqual(['JY25-001', 'SG25-002'])
  })

  it("'전체'는 행을 하나도 잃지 않는다 — 전체 건수 = 각 연도 건수의 합", () => {
    const 전체 = 수주필터(rows, 조건()).length
    const 연도별합 = 연도선택목록(rows)
      .filter((y) => y !== '전체')
      .reduce<number>((s, y) => s + 수주필터(rows, 조건({ 연도: y })).length, 0)
    expect(전체).toBe(4)
    expect(연도별합).toBe(전체)
  })

  it('연도미상을 고르면 지중no 규칙에서 벗어난 행만 나온다', () => {
    expect(수주필터(rows, 조건({ 연도: 연도미상 })).map((r) => r.지중no)).toEqual(['???'])
  })
})

describe('수주필터 — 상태', () => {
  const rows = [
    행({ 지중no: 'AA25-001', 준공여부: true, 이력건수: 0 }),
    행({ 지중no: 'AA25-002', 준공여부: false, 이력건수: 3 }),
    행({ 지중no: 'AA25-003', 준공여부: false, 이력건수: 0 }),
    // 준공 + 이력 둘 다 있는 행 — 판정 우선순위(준공이 이력을 이긴다)를 못 박는다.
    // 이 행이 없으면 아래 '합 = 전체' 테스트가 각 상태 1건씩이라 자명하게 통과해 아무것도 안 잡는다.
    행({ 지중no: 'AA25-004', 준공여부: true, 이력건수: 3 }),
  ]

  it("'진행전'은 이력 0건·미준공만 (시공상태 컬럼이 아니라 이력 기준)", () => {
    expect(수주필터(rows, 조건({ 상태: '진행전' })).map((r) => r.지중no)).toEqual(['AA25-003'])
  })

  it("'진행중'은 미준공 + 이력 1건 이상", () => {
    expect(수주필터(rows, 조건({ 상태: '진행중' })).map((r) => r.지중no)).toEqual(['AA25-002'])
  })

  it("'준공완료'는 준공여부=true (이력 0건이어도 완료)", () => {
    expect(수주필터(rows, 조건({ 상태: '준공완료' })).map((r) => r.지중no)).toEqual(['AA25-001', 'AA25-004'])
  })

  it('세 상태는 서로 배타적이고 합이 전체와 같다 (유령 행이 없다)', () => {
    const 합 = (['진행전', '진행중', '준공완료'] as const).reduce(
      (s, 상태) => s + 수주필터(rows, 조건({ 상태 })).length,
      0,
    )
    expect(합).toBe(rows.length)
  })

  it('시공상태 컬럼이 NULL이어도 어느 한 상태에는 반드시 걸린다', () => {
    const rows = [행({ 시공상태: null, 준공여부: false, 이력건수: 0 })]
    expect(수주필터(rows, 조건({ 상태: '진행전' }))).toHaveLength(1)
  })
})

describe('수주필터 — 공사구분', () => {
  const rows = [
    행({ 지중no: 'AA25-001', 공사구분: '단가' }),
    행({ 지중no: 'AA25-002', 공사구분: '총가' }),
    행({ 지중no: 'AA25-003', 공사구분: '민수' }),
    행({ 지중no: 'AA25-004', 공사구분: '관급' }),
    행({ 지중no: 'AA25-005', 공사구분: null }),
  ]

  it('관급은 민수 필터에 걸린다 (회사 규정 — 민수로 통합)', () => {
    expect(수주필터(rows, 조건({ 공사구분: '민수' })).map((r) => r.지중no)).toEqual(['AA25-003', 'AA25-004'])
  })

  it('총가 필터가 총가만 잡는다', () => {
    expect(수주필터(rows, 조건({ 공사구분: '총가' })).map((r) => r.지중no)).toEqual(['AA25-002'])
  })

  it('공사구분 NULL 행은 어떤 구분 필터에도 안 걸리고 전체에서만 보인다', () => {
    for (const 공사구분 of ['총가', '단가', '민수'] as const) {
      expect(수주필터(rows, 조건({ 공사구분 })).map((r) => r.지중no)).not.toContain('AA25-005')
    }
    expect(수주필터(rows, 조건()).map((r) => r.지중no)).toContain('AA25-005')
  })
})

