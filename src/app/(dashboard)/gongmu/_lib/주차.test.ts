// src/app/(dashboard)/gongmu/_lib/주차.test.ts
import { describe, expect, it } from 'vitest'
import { formatKST } from '@/lib/kst'
import {
  addDays, 월요일Of, 소속월Of, 달의주목록, 주목록기간, 다음달, resolve선택, 금주소속월기간, 조회가능월, 조회월기간,
} from './주차'

describe('날짜 산술', () => {
  it('addDays는 월·연 경계를 넘는다', () => {
    expect(addDays('2026-08-31', 1)).toBe('2026-09-01')
    expect(addDays('2026-12-31', 1)).toBe('2027-01-01')
    expect(addDays('2026-09-01', -1)).toBe('2026-08-31')
  })
  it('월요일Of는 그 주 월요일을 준다 (일요일은 앞 주 월요일)', () => {
    expect(월요일Of('2026-09-28')).toBe('2026-09-28') // 월
    expect(월요일Of('2026-10-04')).toBe('2026-09-28') // 일
    expect(월요일Of('2026-09-01')).toBe('2026-08-31') // 화
  })
})

describe('소속월Of — 금요일의 달', () => {
  it('9/28 주는 금요일 10/2 → 10월', () => expect(소속월Of('2026-09-28')).toBe('2026-10'))
  it('8/31 주는 금요일 9/4 → 9월', () => expect(소속월Of('2026-08-31')).toBe('2026-09'))
  it('4/27 주는 금요일 5/1 → 5월 (ISO 목요일 규칙이면 4월 — 갈리는 사례)', () =>
    expect(소속월Of('2026-04-27')).toBe('2026-05'))
  it('12/28(월)은 금요일이 2027-01-01이어도 해를 넘지 않아 2026-12', () =>
    expect(소속월Of('2026-12-28')).toBe('2026-12'))
})

describe('금주소속월기간 — 대시보드 split 기간', () => {
  it('9/28(월)은 이미 10월: 기간 9/28~11/1 (to 미포함 11/2)', () =>
    expect(금주소속월기간('2026-09-28')).toEqual({ 월: '2026-10', from: '2026-09-28', to: '2026-11-02' }))
  it('9/27(일)은 아직 9월: 기간 8/31~9/27 (to 미포함 9/28)', () =>
    expect(금주소속월기간('2026-09-27')).toEqual({ 월: '2026-09', from: '2026-08-31', to: '2026-09-28' }))
  it('2027-01-01 → 2027-01, 기간은 1/1부터 (12/28~31 은 12월 몫)', () =>
    expect(금주소속월기간('2027-01-01')).toEqual({ 월: '2027-01', from: '2027-01-01', to: '2027-02-01' }))
})

describe('달의주목록', () => {
  it('9월 = 8/31, 9/7, 9/14, 9/21 (9/28 주는 10월)', () => {
    const 주 = 달의주목록('2026-09')
    expect(주.map((w) => w.월요일)).toEqual(['2026-08-31', '2026-09-07', '2026-09-14', '2026-09-21'])
    expect(주[0].label).toBe('1주차 8/31~9/6')
    expect(주[0]).toMatchObject({ 시작: '2026-08-31', 끝: '2026-09-06' })
  })
  it('10월 = 9/28부터 10/26까지 5주', () => {
    const 주 = 달의주목록('2026-10')
    expect(주.map((w) => w.월요일)).toEqual([
      '2026-09-28', '2026-10-05', '2026-10-12', '2026-10-19', '2026-10-26',
    ])
    expect(주[0].label).toBe('1주차 9/28~10/4')
  })
  it('토요일에 시작하는 달은 첫 월요일 주가 전달 소속이면 건너뛴다 (2026-08: 7/27 주는 7월)', () => {
    expect(달의주목록('2026-08')[0].월요일).toBe('2026-08-03')
  })
})

describe('resolve선택', () => {
  it('KST 9/28 월 01:00 (= UTC 9/27 16:00) → 10월 1주차', () => {
    const 오늘 = formatKST(new Date('2026-09-27T16:00:00Z'))
    expect(오늘).toBe('2026-09-28')
    const s = resolve선택(오늘)
    expect(s.월).toBe('2026-10')
    expect(s.선택주.월요일).toBe('2026-09-28')
    expect(s.금주월요일).toBe('2026-09-28')
  })
  it('지난달을 고르면 그 달 마지막 주가 기본 선택', () => {
    const s = resolve선택('2026-09-28', '2026-09')
    expect(s.월).toBe('2026-09')
    expect(s.선택주.월요일).toBe('2026-09-21')
    expect(s.이전가능).toBe(true) // 하한은 2026-01
    expect(s.다음가능).toBe(true)
  })
  it('week 파라미터가 그 달의 주면 그 주를 고른다', () => {
    expect(resolve선택('2026-09-28', '2026-09', '2026-09-07').선택주.월요일).toBe('2026-09-07')
  })
  it('week 파라미터가 그 달의 주가 아니면 무시한다', () => {
    expect(resolve선택('2026-09-28', '2026-09', '2026-09-28').선택주.월요일).toBe('2026-09-21')
  })
  it('하한(2026-01) 이전·금주 달 이후·형식 오류 month는 기본(금주 달)로', () => {
    expect(resolve선택('2026-09-28', '2025-12').월).toBe('2026-10')
    expect(resolve선택('2026-09-28', '2026-11').월).toBe('2026-10')
    expect(resolve선택('2026-09-28', '2026-9').월).toBe('2026-10')
    expect(resolve선택('2026-09-28', '2026-10').다음가능).toBe(false)
  })
  it('연 경계: 2026-12-28 은 12월 5주차 12/28~12/31', () => {
    const s = resolve선택('2026-12-28')
    expect(s.월).toBe('2026-12')
    expect(s.금주월).toBe('2026-12')
    expect(s.선택주).toMatchObject({ 월요일: '2026-12-28', 시작: '2026-12-28', 끝: '2026-12-31', label: '5주차 12/28~12/31' })
  })
})

describe('조회가능월 — 화면과 API가 같이 쓰는 범위 [최소월, 금주월]', () => {
  it('하한·상한 포함', () => {
    expect(조회가능월('2026-01', '2026-11')).toBe(true)
    expect(조회가능월('2026-11', '2026-11')).toBe(true)
  })
  it('하한 앞·상한 뒤는 거절', () => {
    expect(조회가능월('2025-12', '2026-11')).toBe(false)
    expect(조회가능월('2026-12', '2026-11')).toBe(false)
  })
  it('YYYY-MM 형식이 아니면 거절 (문자열 비교가 날짜 비교가 되려면 0 채움 고정폭이어야 한다)', () => {
    for (const m of ['2026-9', '2026-13', '2026-00', '2026-10-01', 'current', '', ' 2026-10']) {
      expect(조회가능월(m, '2027-12')).toBe(false)
    }
  })
})

describe('조회월기간 — ?month= 해석', () => {
  it('지난 달: 2026-10 → 금요일 기준 기간 9/28~11/1 (to 미포함 11/2)', () => {
    expect(조회월기간('2026-10', '2026-11-10')).toEqual({
      ok: true,
      기간: { 월: '2026-10', from: '2026-09-28', to: '2026-11-02' },
    })
  })
  it('9월: 2026-09 → 8/31~9/27 (to 미포함 9/28)', () => {
    expect(조회월기간('2026-09', '2026-11-10')).toEqual({
      ok: true,
      기간: { 월: '2026-09', from: '2026-08-31', to: '2026-09-28' },
    })
  })
  it('금주 달을 고르면 month 없는 응답의 split 과 같은 기간 (금주소속월기간과 같은 값)', () => {
    const r = 조회월기간('2026-11', '2026-11-10')
    expect(r).toEqual({ ok: true, 기간: 금주소속월기간('2026-11-10') })
  })
  it('KST 경계: 2026-11-30(월) 00:30 KST = UTC 11/29 15:30 → 12월이 허용된다 (12월은 12/31에서 끝남)', () => {
    const 오늘 = formatKST(new Date('2026-11-29T15:30:00Z'))
    expect(오늘).toBe('2026-11-30')
    expect(조회월기간('2026-12', 오늘)).toEqual({
      ok: true,
      기간: { 월: '2026-12', from: '2026-11-30', to: '2027-01-01' },
    })
  })
  it('같은 순간을 UTC 날짜(toISOString)로 읽으면 11/29 → 12월이 거절된다 — 호출부가 KST를 넘겨야 하는 이유', () => {
    const utc날짜 = new Date('2026-11-29T15:30:00Z').toISOString().slice(0, 10)
    expect(utc날짜).toBe('2026-11-29')
    expect(조회월기간('2026-12', utc날짜).ok).toBe(false)
  })
  it('상한 뒤(금주 달 다음 달)는 오류, 문구에 허용 범위가 들어간다', () => {
    const r = 조회월기간('2026-12', '2026-11-10')
    expect(r.ok).toBe(false)
    if (!r.ok) expect(r.error).toContain('2026-01~2026-11')
  })
  it('하한 앞은 오류', () => {
    expect(조회월기간('2025-12', '2026-11-10').ok).toBe(false)
  })
  it('형식 오류·빈 문자열은 오류, 문구가 범위 오류와 다르다', () => {
    for (const m of ['2026-9', '2026-13', '', 'current', '2026-10-01']) {
      const r = 조회월기간(m, '2026-11-10')
      expect(r.ok).toBe(false)
      if (!r.ok) expect(r.error).toContain('YYYY-MM')
    }
  })
  it('연 경계: 2026-12-28(월)이면 금주 달은 아직 2026-12 → 2027-01 은 거절', () => {
    expect(조회월기간('2027-01', '2026-12-28').ok).toBe(false)
  })
  it('연 경계: 2027-01-01 이면 2027-01 허용, 기간 1/1~1/31 (to 미포함 2/1)', () => {
    expect(조회월기간('2027-01', '2027-01-01')).toEqual({
      ok: true,
      기간: { 월: '2027-01', from: '2027-01-01', to: '2027-02-01' },
    })
  })
})

describe('해를 넘기지 않는 주 (2026-11-12)', () => {
  it('2025-12-29 주: 12/29~31 은 2025-12 마지막 주, 1/1~1/4 는 2026-01 1주차', () => {
    expect(달의주목록('2025-12').at(-1)).toEqual({
      월요일: '2025-12-29', 시작: '2025-12-29', 끝: '2025-12-31', 소속월: '2025-12', 주차: 5, label: '5주차 12/29~12/31',
    })
    expect(달의주목록('2026-01')[0]).toEqual({
      월요일: '2025-12-29', 시작: '2026-01-01', 끝: '2026-01-04', 소속월: '2026-01', 주차: 1, label: '1주차 1/1~1/4',
    })
  })
  it('2026-01 기간 = 1/1 ~ 2/1 (to 미포함 2/2) — 이관행 12/30·31 이 빠진다', () =>
    expect(금주소속월기간('2026-01-15')).toEqual({ 월: '2026-01', from: '2026-01-01', to: '2026-02-02' }))
  it('2026-12 기간 = 11/30 ~ 12/31 (to 미포함 2027-01-01)', () =>
    expect(금주소속월기간('2026-12-30')).toEqual({ 월: '2026-12', from: '2026-11-30', to: '2027-01-01' }))
  it('2026-12-28 주의 두 조각은 열쇠(월요일)가 같고 범위가 다르다', () => {
    const 십이월 = 달의주목록('2026-12').at(-1)!
    const 일월 = 달의주목록('2027-01')[0]
    expect(십이월.월요일).toBe(일월.월요일)
    expect([십이월.시작, 십이월.끝, 일월.시작, 일월.끝]).toEqual(['2026-12-28', '2026-12-31', '2027-01-01', '2027-01-03'])
  })
  it('금요일이 12월인 주도 자른다: 2027-12-27 주 → 12/27~31 은 2027-12, 1/1~2 는 2028-01', () => {
    expect(달의주목록('2027-12').at(-1)).toMatchObject({ 시작: '2027-12-27', 끝: '2027-12-31' })
    expect(달의주목록('2028-01')[0]).toMatchObject({ 월요일: '2027-12-27', 시작: '2028-01-01', 끝: '2028-01-02', label: '1주차 1/1~1/2' })
  })
  it('해 경계가 아닌 주는 기존 규칙 그대로 (금요일의 달)', () => {
    expect(소속월Of('2026-04-27')).toBe('2026-05')
    expect(소속월Of('2026-10-04')).toBe('2026-10') // 9/28 주의 일요일
  })
  it('2025-12 ~ 2028-02 모든 달의 기간이 빈틈·겹침 없이 이어진다', () => {
    let m = '2025-12'
    let prevTo: string | null = null
    while (m <= '2028-02') {
      const { from, to } = 주목록기간(달의주목록(m))
      if (prevTo) expect(from).toBe(prevTo)
      prevTo = to
      m = 다음달(m)
    }
  })
  it('오늘이 잘린 주 안: 12/30 → 금주월 2026-12, 2027-01-02 → 2027-01', () => {
    expect(resolve선택('2026-12-30')).toMatchObject({ 월: '2026-12', 금주월: '2026-12', 금주월요일: '2026-12-28' })
    const s = resolve선택('2027-01-02')
    expect(s).toMatchObject({ 월: '2027-01', 금주월: '2027-01', 금주월요일: '2026-12-28' })
    expect(s.선택주).toMatchObject({ 시작: '2027-01-01', 끝: '2027-01-03' })
  })
  it('KST 00:30 경계: 2027-01-01 00:30 KST(= UTC 12/31 15:30) → 2027-01. UTC 날짜를 넘기면 12월로 밀린다', () => {
    const 순간 = new Date('2026-12-31T15:30:00Z')
    expect(resolve선택(formatKST(순간)).월).toBe('2027-01')
    expect(조회월기간('2027-01', formatKST(순간)).ok).toBe(true)
    // 서버 시계(UTC) 날짜를 넘기는 실수 — 이번 달이 거절된다
    const utc날짜 = 순간.toISOString().slice(0, 10) // '2026-12-31'
    expect(resolve선택(utc날짜).월).toBe('2026-12')
    expect(조회월기간('2027-01', utc날짜).ok).toBe(false)
  })
  it('최소월 2026-01: 1월 공무 화면은 ◀ 이 꺼진다', () =>
    expect(resolve선택('2026-11-12', '2026-01')).toMatchObject({ 월: '2026-01', 이전가능: false }))
})
